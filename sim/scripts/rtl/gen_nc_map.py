"""Generate rtl/ofdm_nc/phy/ofdm_nc_map.vh from the NC reference model.

  python -I -B scripts/rtl/gen_nc_map.py [--check]

The header holds portable Verilog-2001 functions (included inside modules):
nc_ord2bin, nc_bin2group (15 = not a data bin), nc_popcount11,
nc_first_unmasked, nc_next_unmasked (11 = none).  --check compares the file
on disk with the generated text and exits 1 on any difference.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from models.ofdm import core          # noqa: E402
from models.ofdm_nc import nc         # noqa: E402

OUT = ROOT.parent / 'src' / 'rtl' / 'ofdm' / 'phy' / 'ofdm_nc_map.vh'


def text():
    lines = ['// Generated by scripts/rtl/gen_nc_map.py from models/ofdm_nc/nc.py; do not edit.',
             '// Data carriers in signed order (-48..48 without pilots/DC), 11 groups of 8.',
             'function [6:0] nc_ord2bin;', '  input [6:0] ord;', '  begin', '    case (ord)']
    for d, k in enumerate(nc.DATA_SIGNED):
        lines.append("      7'd%d: nc_ord2bin = 7'd%d;" % (d, k % core.NFFT))
    lines += ["      default: nc_ord2bin = 7'd0;", '    endcase', '  end', 'endfunction', '',
              'function [3:0] nc_bin2group;', '  input [6:0] bin;', '  begin', '    case (bin)']
    for b in range(core.NFFT):
        g = nc.group_of_bin(b)
        if g is not None:
            lines.append("      7'd%d: nc_bin2group = 4'd%d;" % (b, g))
    lines += ["      default: nc_bin2group = 4'd15;", '    endcase', '  end', 'endfunction', '',
              'function [3:0] nc_popcount11;', '  input [10:0] mask;', '  integer i;', '  begin',
              '    nc_popcount11 = 0;',
              '    for (i = 0; i < 11; i = i + 1) nc_popcount11 = nc_popcount11 + mask[i];',
              '  end', 'endfunction', '',
              'function [3:0] nc_next_unmasked;      // first unmasked group > g, 11 if none',
              '  input [10:0] mask;', '  input [3:0] g;', '  integer i;', '  begin',
              "    nc_next_unmasked = 4'd11;",
              '    for (i = 10; i >= 0; i = i - 1)',
              "      if (i > g && !mask[i]) nc_next_unmasked = i;",
              '  end', 'endfunction', '',
              'function [3:0] nc_first_unmasked;', '  input [10:0] mask;', '  integer i;', '  begin',
              "    nc_first_unmasked = 4'd11;",
              '    for (i = 10; i >= 0; i = i - 1)',
              "      if (!mask[i]) nc_first_unmasked = i;",
              '  end', 'endfunction', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    body = text()
    if a.check:
        same = OUT.exists() and OUT.read_text(encoding='ascii') == body
        print('NC_MAP_CHECK', 'PASS' if same else 'FAIL', OUT)
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body, encoding='ascii', newline='\n')
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
